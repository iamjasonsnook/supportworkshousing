#!/usr/bin/env node
/**
 * Copy the built Crossings dashboard into this repo as a module the admin
 * API can serve.
 *
 * The dashboard is built in the swh-asset-management repo, which is where
 * its data and tie-out tests live. This brings the finished single-file
 * build across so /api/admin/crossings can return it behind auth.
 *
 * Why a .js module and not a file in public/: anything under public/ is
 * served by the CDN to anyone who asks. This has to be reachable only
 * through the authenticated route, so it ships inside the function bundle.
 * The leading underscore matches api/_cors.js and api/_email.js -- those
 * are helpers, not routes.
 *
 * Why base64: the payload is a complete HTML document containing both
 * backticks and ${ sequences. Encoding it sidesteps every escaping
 * question rather than answering them one at a time.
 *
 * Usage:
 *   node scripts/sync-crossings-dashboard.mjs [path/to/crossings-dashboard.html]
 *
 * This is the interim arrangement. The proper source is the asset
 * management Supabase project: once that is stood up, this route should
 * query it and render on demand, and this generated file goes away along
 * with the half-megabyte it adds to the repo on every data load.
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_SRC = resolve(
  HERE, '..', '..', 'swh-asset-management', 'dashboard', 'dist', 'crossings-dashboard.html'
);
const OUT = resolve(HERE, '..', 'api', 'admin', '_crossings-dashboard.js');

const src = resolve(process.argv[2] || DEFAULT_SRC);

let html;
try {
  html = readFileSync(src);
} catch {
  console.error(`Could not read ${src}`);
  console.error('Build it first: python3 dashboard/build_standalone.py in swh-asset-management');
  process.exit(1);
}

// A standalone build inlines its CSS, JS, logo and data. If any of those
// are still external the page will half-render behind the login, which is
// a confusing failure to debug, so check here instead.
const text = html.toString('utf8');
for (const [needle, what] of [
  ['window.__SWH_DATA__', 'inlined data payload'],
  ['data:image/svg+xml', 'inlined logo'],
  ['<style>', 'inlined stylesheet'],
]) {
  if (!text.includes(needle)) {
    console.error(`Refusing to sync: ${src} is missing its ${what}.`);
    console.error('That is the hosted build, not the standalone one.');
    process.exit(1);
  }
}
if (text.includes('src="app.js"') || text.includes('href="styles.css"')) {
  console.error(`Refusing to sync: ${src} still links external assets.`);
  process.exit(1);
}

const encoded = html.toString('base64');
writeFileSync(OUT, `// Generated by scripts/sync-crossings-dashboard.mjs. Do not hand-edit.
//
// The Crossings asset management dashboard, base64-encoded. Served only by
// GET /api/admin/crossings, after a token verifies. Source of truth is the
// swh-asset-management repo.
//
// Built from: ${src.replace(process.env.HOME || '~', '~')}
// Source size: ${(html.length / 1024).toFixed(1)} KB
export default '${encoded}';
`);

console.log(`synced ${(html.length / 1024).toFixed(1)} KB ->`,
            `api/admin/_crossings-dashboard.js (${(statSync(OUT).size / 1024).toFixed(1)} KB)`);
